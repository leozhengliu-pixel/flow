#!/usr/bin/env node
// Generates the typed layer of @flow/sdk from docs/openapi.json:
//   src/generated/models.ts      one TypeScript type per component schema
//   src/generated/operations.ts  request/response types, an operation table and
//                                the `FlowApi` class (one method per typed operation)
//   src/generated/index.ts       re-exports
//
//   node sdk/typescript/scripts/generate.mjs           # write the files
//   node sdk/typescript/scripts/generate.mjs --check   # CI: exit 1 when they are stale
//   node sdk/typescript/scripts/generate.mjs --spec path/to/openapi.json
//
// Run it from anywhere; paths are resolved relative to this file. Output is
// deterministic and needs no dependencies.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const packageRoot = path.resolve(here, '..')
const repoRoot = path.resolve(packageRoot, '../..')
const outDir = path.join(packageRoot, 'src/generated')

const args = process.argv.slice(2)
const check = args.includes('--check')
const specFlag = args.indexOf('--spec')
const specPath = specFlag >= 0 ? path.resolve(process.cwd(), args[specFlag + 1] ?? '') : path.join(repoRoot, 'docs/openapi.json')
const spec = JSON.parse(readFileSync(specPath, 'utf8'))

const banner = [
  '// Generated by sdk/typescript/scripts/generate.mjs from docs/openapi.json.',
  '// Do not edit by hand: change the API contract, then run',
  '//   node sdk/typescript/scripts/generate.mjs',
  '',
].join('\n')

// Schema names that would collide with globals or SDK classes.
const renamed = { Error: 'ErrorResponse' }
const typeName = name => renamed[name] ?? name

const schemas = spec.components?.schemas ?? {}
const componentParameters = spec.components?.parameters ?? {}

// ---------------------------------------------------------------------------
// JSON Schema -> TypeScript
// ---------------------------------------------------------------------------

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const propertyKey = key => (identifier.test(key) ? key : JSON.stringify(key))

function comment(text, indent) {
  if (!text) return ''
  const clean = String(text).replace(/\*\//g, '*\\/').trim()
  const lines = clean.split('\n').map(line => line.trimEnd())
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`
  return `${indent}/**\n${lines.map(line => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`
}

function wrapUnion(type) {
  return /[|&]/.test(type) ? `(${type})` : type
}

function schemaType(schema, indent = '') {
  if (!schema || typeof schema !== 'object' || Object.keys(schema).length === 0) return 'unknown'
  if (schema.$ref) return typeName(schema.$ref.split('/').pop())
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ')
  const variants = schema.anyOf ?? schema.oneOf
  if (variants) return unique(variants.map(variant => schemaType(variant, indent))).join(' | ')
  if (schema.allOf) return schema.allOf.map(variant => wrapUnion(schemaType(variant, indent))).join(' & ')
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  if (types.length === 0) return schema.properties ? objectType(schema, indent) : 'unknown'
  return unique(types.map(type => primitiveType(type, schema, indent))).join(' | ')
}

function primitiveType(type, schema, indent) {
  switch (type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `${wrapUnion(schemaType(schema.items, indent))}[]`
    case 'object':
      return objectType(schema, indent)
    default:
      return 'unknown'
  }
}

function objectType(schema, indent) {
  const properties = schema.properties ? Object.entries(schema.properties) : []
  if (properties.length === 0) {
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object' && Object.keys(schema.additionalProperties).length) {
      return `Record<string, ${schemaType(schema.additionalProperties, indent)}>`
    }
    return 'Record<string, unknown>'
  }
  const required = new Set(schema.required ?? [])
  const inner = `${indent}  `
  const lines = properties.map(([key, value]) => `${comment(value?.description, inner)}${inner}${propertyKey(key)}${required.has(key) ? '' : '?'}: ${schemaType(value, inner)}`)
  const extra = schema.additionalProperties ? [`${inner}[key: string]: unknown`] : []
  return `{\n${[...lines, ...extra].join('\n')}\n${indent}}`
}

function unique(values) {
  return [...new Set(values)]
}

function emitModels() {
  let out = `${banner}\n`
  out += `/** Version of the OpenAPI document these types were generated from. */\n`
  out += `export const SPEC_VERSION = ${JSON.stringify(spec.info?.version ?? '')}\n\n`
  for (const name of Object.keys(schemas).sort()) {
    const schema = schemas[name]
    const exported = typeName(name)
    out += comment(schema.description, '')
    const isObject = schema.type === 'object' && schema.properties && Object.keys(schema.properties).length > 0
    if (isObject) {
      const required = new Set(schema.required ?? [])
      out += `export interface ${exported} {\n`
      for (const [key, value] of Object.entries(schema.properties)) {
        out += `${comment(value?.description, '  ')}  ${propertyKey(key)}${required.has(key) ? '' : '?'}: ${schemaType(value, '  ')}\n`
      }
      if (schema.additionalProperties) out += '  [key: string]: unknown\n'
      out += '}\n\n'
    } else {
      out += `export type ${exported} = ${schemaType(schema)}\n\n`
    }
  }
  return out.trimEnd() + '\n'
}

// ---------------------------------------------------------------------------
// Operations
// ---------------------------------------------------------------------------

function resolveParameter(parameter) {
  if (parameter.$ref) return componentParameters[parameter.$ref.split('/').pop()]
  return parameter
}

function referencesSchema(value) {
  return JSON.stringify(value).includes('#/components/schemas/')
}

function camelCase(operationId) {
  return operationId.replace(/_([a-zA-Z0-9])/g, (_, letter) => letter.toUpperCase())
}

function pascalCase(value) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function parameterType(parameter) {
  if (parameter.schema) return schemaType(parameter.schema, '    ')
  const json = parameter.content?.['application/json']?.schema
  return json ? schemaType(json, '    ') : 'unknown'
}

function successResponses(operation) {
  return Object.entries(operation.responses ?? {})
    .filter(([status]) => /^2\d\d$/.test(status))
    .sort(([left], [right]) => left.localeCompare(right))
}

const operations = []
for (const [routePath, item] of Object.entries(spec.paths ?? {})) {
  for (const [method, operation] of Object.entries(item)) {
    if (!operation || typeof operation !== 'object' || !operation.responses) continue
    if (!referencesSchema({ responses: operation.responses, requestBody: operation.requestBody })) continue
    const parameters = (operation.parameters ?? []).map(resolveParameter).filter(Boolean)
    const successes = successResponses(operation)
    const responseSchemas = unique(
      successes
        .map(([, response]) => response.content?.['application/json']?.schema)
        .filter(Boolean)
        .map(schema => schemaType(schema)),
    )
    const body = operation.requestBody?.content?.['application/json']
    operations.push({
      method: method.toUpperCase(),
      path: routePath,
      id: operation.operationId,
      name: camelCase(operation.operationId),
      summary: operation.summary ?? '',
      description: operation.description ?? '',
      deprecated: Boolean(operation.deprecated),
      pathParameters: parameters.filter(parameter => parameter.in === 'path'),
      queryParameters: parameters.filter(parameter => parameter.in === 'query'),
      bodyType: body ? schemaType(body.schema) : undefined,
      bodyRequired: Boolean(operation.requestBody?.required),
      responseType: responseSchemas.length ? responseSchemas.join(' | ') : 'void',
      statuses: successes.map(([status]) => Number(status)),
      tags: operation.tags ?? [],
    })
  }
}
operations.sort((left, right) => left.path.localeCompare(right.path) || left.method.localeCompare(right.method))

const names = new Set()
for (const operation of operations) {
  if (names.has(operation.name)) throw new Error(`duplicate operation name ${operation.name}`)
  names.add(operation.name)
}

function queryInterface(operation) {
  if (operation.queryParameters.length === 0) return undefined
  const name = `${pascalCase(operation.name)}Query`
  let out = ''
  out += `/** Query parameters of \`${operation.method} ${operation.path}\`. */\n`
  out += `export interface ${name} {\n`
  for (const parameter of operation.queryParameters) {
    out += comment(parameter.description, '  ')
    out += `  ${propertyKey(parameter.name)}${parameter.required ? '' : '?'}: ${parameterType(parameter)}\n`
  }
  out += '}\n\n'
  return { name, text: out, required: operation.queryParameters.some(parameter => parameter.required) }
}

function emitOperations() {
  const referenced = new Set()
  const collect = text => {
    for (const match of text.matchAll(/\b[A-Z][A-Za-z0-9]*\b/g)) if (schemas[match[0]] || Object.values(renamed).includes(match[0])) referenced.add(match[0])
  }

  const blocks = []
  const operationTable = []
  const methods = []
  for (const operation of operations) {
    const query = queryInterface(operation)
    if (query) blocks.push(query.text)
    const requestName = `${pascalCase(operation.name)}Request`
    const fields = []
    if (operation.pathParameters.length) {
      fields.push({ text: `  path: { ${operation.pathParameters.map(parameter => `${propertyKey(parameter.name)}: string`).join('; ')} }`, required: true })
    }
    if (query) fields.push({ text: `  query${query.required ? '' : '?'}: ${query.name}`, required: query.required })
    if (operation.bodyType) fields.push({ text: `  body${operation.bodyRequired ? '' : '?'}: ${operation.bodyType}`, required: operation.bodyRequired })
    const requestRequired = fields.some(field => field.required)
    if (fields.length) blocks.push(`/** Arguments of \`${operation.name}\`. */\nexport interface ${requestName} {\n${fields.map(field => field.text).join('\n')}\n}\n\n`)
    collect(`${operation.bodyType ?? ''} ${operation.responseType}`)
    for (const parameter of operation.queryParameters) collect(parameterType(parameter))
    operationTable.push(
      `  ${operation.name}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)}, operationId: ${JSON.stringify(operation.id)}, successStatuses: [${operation.statuses.join(', ')}] },`,
    )

    const doc = [`${operation.method} ${operation.path}`, operation.summary, operation.description, operation.deprecated ? '@deprecated' : '']
      .filter(Boolean)
      .map((line, index) => (index === 0 ? `\`${line}\`` : line))
      .join('\n')
    let method = comment(doc, '  ')
    const requestParam = fields.length ? `request${requestRequired ? '' : '?'}: ${requestName}, ` : ''
    method += `  ${operation.name}(${requestParam}options?: RequestOptions): Promise<${operation.responseType}> {\n`
    const parts = [`method: ${JSON.stringify(operation.method)}`, `path: ${JSON.stringify(operation.path)}`]
    if (operation.pathParameters.length) parts.push('pathParams: request.path')
    if (query) parts.push(query.required ? 'query: request.query' : 'query: request?.query')
    if (operation.bodyType) parts.push(operation.bodyRequired ? 'body: request.body' : 'body: request?.body')
    if (operation.responseType === 'void') parts.push("expect: 'none'")
    method += `    return this.transport.request({ ${parts.join(', ')}, ...options })\n  }\n`
    methods.push(method)
  }

  let out = `${banner}\n`
  const modelImports = [...referenced].sort()
  if (modelImports.length) out += `import type {\n${modelImports.map(name => `  ${name},`).join('\n')}\n} from './models.js'\n`
  out += "import type { ApiTransport, RequestOptions } from '../http.js'\n\n"
  out += blocks.join('')
  out += '/** Method, path and success statuses of every typed operation. */\n'
  out += `export const operations = {\n${operationTable.join('\n')}\n} as const\n\n`
  out += 'export type OperationName = keyof typeof operations\n\n'
  out += '/** One method per typed operation of the OpenAPI document. `FlowClient` wraps it with pagination and helpers; use this class for the exact wire contract. */\n'
  out += `export class FlowApi {\n  constructor(private readonly transport: ApiTransport) {}\n\n${methods.join('\n')}}\n`
  return out
}

function emitIndex() {
  return `${banner}\nexport * from './models.js'\nexport * from './operations.js'\n`
}

// ---------------------------------------------------------------------------

const files = {
  'models.ts': emitModels(),
  'operations.ts': emitOperations(),
  'index.ts': emitIndex(),
}

if (check) {
  const stale = []
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(outDir, name)
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) stale.push(path.relative(repoRoot, file))
  }
  if (stale.length) {
    console.error(`Generated SDK files are stale:\n${stale.map(file => `  ${file}`).join('\n')}\nRun: node sdk/typescript/scripts/generate.mjs`)
    process.exit(1)
  }
  console.log(`SDK generated files are up to date (${operations.length} operations, ${Object.keys(schemas).length} schemas).`)
} else {
  mkdirSync(outDir, { recursive: true })
  for (const [name, content] of Object.entries(files)) writeFileSync(path.join(outDir, name), content)
  console.log(`Wrote ${Object.keys(files).length} files to ${path.relative(repoRoot, outDir)} (${operations.length} operations, ${Object.keys(schemas).length} schemas).`)
}
