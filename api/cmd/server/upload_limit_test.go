// withUploadLimit sets the upload limit (server.storage.uploadMaxBytes in the config file) for one test.
func withUploadLimit(t *testing.T, limit int64) {
	t.Helper()
	previous := uploadMaxBytes.Load()
	uploadMaxBytes.Store(limit)
	t.Cleanup(func() { uploadMaxBytes.Store(previous) })
}

// streamedUploadBody is a multipart upload body written while it is read: a
// file part of size generated bytes between the given fields. Nothing holds
// the whole body; done closes once it was read to the end (or reading
// stopped). Close the reader when the handler returns.
func streamedUploadBody(filename string, size int64, before, after map[string]string) (*io.PipeReader, string, <-chan struct{}) {
	reader, writer := io.Pipe()
	form := multipart.NewWriter(writer)
	done := make(chan struct{})
	go func() {
		defer close(done)
		writer.CloseWithError(func() error {
			for name, value := range before {
				if err := form.WriteField(name, value); err != nil {
					return err
				}
			}
			part, err := form.CreateFormFile("file", filename)
			if err != nil {
				return err
			}
			chunk := []byte(strings.Repeat("flow upload streaming check ", 2048))
			for remaining := size; remaining > 0; {
				n := min(remaining, int64(len(chunk)))
				if _, err := part.Write(chunk[:n]); err != nil {
					return err
				}
				remaining -= n
			}
			for name, value := range after {
				if err := form.WriteField(name, value); err != nil {
					return err
				}
			}
			return form.Close()
		}())
	}()
	return reader, form.FormDataContentType(), done
}

// heapGrowthWhile reports the largest growth of the live heap over its level
// before run, sampled every few milliseconds until stop closes.
func heapGrowthWhile(stop <-chan struct{}, run func()) uint64 {
	runtime.GC()
	var stats runtime.MemStats
	runtime.ReadMemStats(&stats)
	baseline, peak := stats.HeapAlloc, stats.HeapAlloc
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		ticker := time.NewTicker(5 * time.Millisecond)
		defer ticker.Stop()
		for {
			var sample runtime.MemStats
			runtime.ReadMemStats(&sample)
			peak = max(peak, sample.HeapAlloc)
			select {
			case <-stop:
				return
			case <-ticker.C:
			}
		}
	}()
	run()
	wg.Wait()
	if peak < baseline {
		return 0
	}
	return peak - baseline
}

func uploadLimitTestServer(t *testing.T) (http.Handler, string) {
	t.Helper()
	repository, err := store.OpenSQLiteTestFixture(filepath.Join(t.TempDir(), "flow.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { repository.Close() })
	uploads := t.TempDir()
	return newHandler(&server{store: repository, uploadPath: uploads, authDisabled: true}), uploads
}

func storedObjects(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	names := []string{}
	for _, entry := range entries {
		names = append(names, entry.Name())
	}
	return names
}

func streamUpload(t *testing.T, handler http.Handler, path, filename string, size int64, before, after map[string]string) (*httptest.ResponseRecorder, uint64) {
	t.Helper()
	body, contentType, done := streamedUploadBody(filename, size, before, after)
	request := httptest.NewRequest(http.MethodPost, path, body)
	request.Header.Set("Content-Type", contentType)
	recorder := httptest.NewRecorder()
	growth := heapGrowthWhile(done, func() {
		handler.ServeHTTP(recorder, request)
		body.Close()
	})
	return recorder, growth
}

func TestUploadLimitDefaultAndBootstrap(t *testing.T) {
	if uploadLimit() != 100<<20 {
		t.Fatalf("default upload limit = %d, want 100 MiB", uploadLimit())
	}
	if uploadLimitText(100<<20) != "100 MB" || uploadLimitText(3<<19) != "1.5 MB" {
		t.Fatalf("limit texts = %q %q", uploadLimitText(100<<20), uploadLimitText(3<<19))
	}
	handler, _ := uploadLimitTestServer(t)
	if bootstrap := requestJSON[domain.Bootstrap](t, handler, http.MethodGet, "/api/bootstrap", nil, http.StatusOK); bootstrap.UploadMaxBytes != 100<<20 {
		t.Fatalf("bootstrap upload limit = %d", bootstrap.UploadMaxBytes)
	}
	withUploadLimit(t, 250<<20)
	if bootstrap := requestJSON[domain.Bootstrap](t, handler, http.MethodGet, "/api/bootstrap", nil, http.StatusOK); bootstrap.UploadMaxBytes != 250<<20 {
		t.Fatalf("configured bootstrap upload limit = %d", bootstrap.UploadMaxBytes)
	}
}

// A file of about 100 MB streams into storage: the heap does not grow by
// anything near the file's size while the request is read.
func TestAttachmentUploadStreamsWithBoundedMemory(t *testing.T) {
	handler, uploads := uploadLimitTestServer(t)
	issue := requestJSON[domain.Issue](t, handler, http.MethodPost, "/api/issues", map[string]any{"title": "Large upload"}, http.StatusCreated)
	const size = 100<<20 - 4096
	recorder, growth := streamUpload(t, handler, "/api/issues/"+issue.ID+"/attachments", "large.bin", size, map[string]string{"note": "before"}, map[string]string{"embed": "0"})
	if recorder.Code != http.StatusCreated {
		t.Fatalf("upload status %d: %s", recorder.Code, recorder.Body.String())
	}
	var attachment domain.Attachment
	if err := json.Unmarshal(recorder.Body.Bytes(), &attachment); err != nil || attachment.Size != size || attachment.Title != "large.bin" || attachment.ContentType != "application/octet-stream" {
		t.Fatalf("attachment = %#v err=%v", attachment, err)
	}
	info, err := os.Stat(filepath.Join(uploads, strings.TrimPrefix(attachment.URL, "/uploads/")))
	if err != nil || info.Size() != size {
		t.Fatalf("stored object: %v %v", info, err)
	}
	t.Logf("peak heap growth while streaming %d bytes: %.1f MiB", size, float64(growth)/(1<<20))
	if growth > 16<<20 {
		t.Fatalf("heap grew by %d bytes while streaming the upload", growth)
	}
	// embed=0 after the file part is still read: the file is not put into the description.
	stored := findIssue(t, requestJSON[domain.Bootstrap](t, handler, http.MethodGet, "/api/bootstrap", nil, http.StatusOK).Issues, issue.ID)
	if strings.Contains(stored.Description, attachment.URL) || len(stored.Attachments) != 1 {
		t.Fatalf("embed=0 was ignored: %q %d", stored.Description, len(stored.Attachments))
	}
}

// One byte over the limit is refused with 413 and leaves no object behind.
func TestAttachmentUploadOverLimitLeavesNoObject(t *testing.T) {
	handler, uploads := uploadLimitTestServer(t)
	issue := requestJSON[domain.Issue](t, handler, http.MethodPost, "/api/issues", map[string]any{"title": "Oversized upload"}, http.StatusCreated)
	recorder, growth := streamUpload(t, handler, "/api/issues/"+issue.ID+"/attachments", "huge.bin", 100<<20+1, nil, nil)
	if recorder.Code != http.StatusRequestEntityTooLarge || !strings.Contains(recorder.Body.String(), "attachment exceeds 100 MB") {
		t.Fatalf("oversized upload = %d %s", recorder.Code, recorder.Body.String())
	}
	if objects := storedObjects(t, uploads); len(objects) != 0 {
		t.Fatalf("oversized upload left objects %v", objects)
	}
	t.Logf("peak heap growth while refusing %d bytes: %.1f MiB", 100<<20+1, float64(growth)/(1<<20))
	if growth > 16<<20 {
		t.Fatalf("heap grew by %d bytes while refusing the upload", growth)
	}
	if stored := findIssue(t, requestJSON[domain.Bootstrap](t, handler, http.MethodGet, "/api/bootstrap", nil, http.StatusOK).Issues, issue.ID); len(stored.Attachments) != 0 {
		t.Fatalf("oversized upload was recorded: %#v", stored.Attachments)
	}
}

// A configured limit applies to every upload path: a file at the limit is
// stored, one byte more is refused without leaving an object.
func TestConfiguredUploadLimitAppliesToEveryUploadPath(t *testing.T) {
	withUploadLimit(t, 2<<20)
	handler, uploads := uploadLimitTestServer(t)
	issue := requestJSON[domain.Issue](t, handler, http.MethodPost, "/api/issues", map[string]any{"title": "Configured limit"}, http.StatusCreated)
	document := requestJSON[domain.Document](t, handler, http.MethodPost, "/api/documents", map[string]any{"title": "Configured limit"}, http.StatusCreated)
	bootstrap := requestJSON[domain.Bootstrap](t, handler, http.MethodGet, "/api/bootstrap", nil, http.StatusOK)
	if len(bootstrap.Projects) == 0 {
		t.Fatal("fixture has no project")
	}
	paths := []string{
		"/api/issues/" + issue.ID + "/attachments",
		"/api/documents/" + document.ID + "/attachments",
		"/api/projects/" + bootstrap.Projects[0].ID + "/comment-attachments",
	}
	for _, path := range paths {
		before := len(storedObjects(t, uploads))
		recorder, _ := streamUpload(t, handler, path, "limit.bin", 2<<20, nil, nil)
		if recorder.Code != http.StatusCreated {
			t.Fatalf("%s at the limit = %d %s", path, recorder.Code, recorder.Body.String())
		}
		if after := len(storedObjects(t, uploads)); after != before+1 {
			t.Fatalf("%s stored %d objects", path, after-before)
		}
		recorder, _ = streamUpload(t, handler, path, "over.bin", 2<<20+1, nil, nil)
		if recorder.Code != http.StatusRequestEntityTooLarge || !strings.Contains(recorder.Body.String(), "attachment exceeds 2 MB") {
			t.Fatalf("%s over the limit = %d %s", path, recorder.Code, recorder.Body.String())
		}
		if after := len(storedObjects(t, uploads)); after != before+1 {
			t.Fatalf("%s left an oversized object", path)
		}
	}
	// Prepared uploads (REST and MCP) are refused at preparation.
	recorder := httptest.NewRecorder()
	request := httptest.NewRequest(http.MethodPost, "/api/files", strings.NewReader(`{"filename":"over.bin","contentType":"application/octet-stream","size":2097153}`))
	request.Header.Set("Content-Type", "application/json")
	handler.ServeHTTP(recorder, request)
	if recorder.Code != http.StatusBadRequest || !strings.Contains(recorder.Body.String(), "size must be between 0 and 2 MB") {
		t.Fatalf("prepared upload over the limit = %d %s", recorder.Code, recorder.Body.String())
	}
}

// Malformed forms keep their errors: no file part is 400 "file is required",
// a body that is not a multipart form or is cut off is 400 "invalid
// attachment", and neither leaves an object.
func TestAttachmentUploadFormErrors(t *testing.T) {
	handler, uploads := uploadLimitTestServer(t)
	issue := requestJSON[domain.Issue](t, handler, http.MethodPost, "/api/issues", map[string]any{"title": "Form errors"}, http.StatusCreated)
	path := "/api/issues/" + issue.ID + "/attachments"
	send := func(body io.Reader, contentType string) *httptest.ResponseRecorder {
		request := httptest.NewRequest(http.MethodPost, path, body)
		request.Header.Set("Content-Type", contentType)
		recorder := httptest.NewRecorder()
		handler.ServeHTTP(recorder, request)
		return recorder
	}
	var fieldsOnly strings.Builder
	form := multipart.NewWriter(&fieldsOnly)
	_ = form.WriteField("embed", "0")
	_ = form.Close()
	if recorder := send(strings.NewReader(fieldsOnly.String()), form.FormDataContentType()); recorder.Code != http.StatusBadRequest || !strings.Contains(recorder.Body.String(), "file is required") {
		t.Fatalf("form without a file = %d %s", recorder.Code, recorder.Body.String())
	}
	if recorder := send(strings.NewReader(`{"file":"x"}`), "application/json"); recorder.Code != http.StatusBadRequest || !strings.Contains(recorder.Body.String(), "invalid attachment") {
		t.Fatalf("JSON body = %d %s", recorder.Code, recorder.Body.String())
	}
	var cut strings.Builder
	form = multipart.NewWriter(&cut)
	part, _ := form.CreateFormFile("file", "cut.bin")
	_, _ = part.Write([]byte(strings.Repeat("x", 4096)))
	if recorder := send(strings.NewReader(cut.String()), form.FormDataContentType()); recorder.Code != http.StatusBadRequest || !strings.Contains(recorder.Body.String(), "invalid attachment") {
		t.Fatalf("cut off body = %d %s", recorder.Code, recorder.Body.String())
	}
	if objects := storedObjects(t, uploads); len(objects) != 0 {
		t.Fatalf("failed uploads left objects %v", objects)
	}
}
