type scaleP21M3PointOperation struct {
	name, kind, id, body string
	seed                 func(*domain.Bootstrap, domain.User)
	handler              func(*server, http.ResponseWriter, *http.Request)
	readKeys             func(domain.User) []store.RecordKey
	otherKeys            []store.RecordKey
}

func scaleP21M3Fingerprint(t *testing.T, repo *store.SQLiteStore, workspace, kind string) string {
	t.Helper()
	digest := sha256.New()
	if err := repo.StreamMetadataRecords(t.Context(), workspace, kind, func(_ store.RecordKey, reader io.Reader) error {
		_, err := io.Copy(digest, reader)
		return err
	}); err != nil {
		t.Fatal(err)
	}
	return string(digest.Sum(nil))
}

// These timestamps are generated by the point callbacks under comparison.
// Resource IDs, actors, permissions, references and nil/empty shapes remain.
func scaleP21M3PointJSON(t *testing.T, value any) any {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	result := scaleP21M3JSON(t, raw)
	var normalize func(any)
	normalize = func(value any) {
		switch item := value.(type) {
		case map[string]any:
			for key, value := range item {
				if key == "updatedAt" || key == "completedAt" || key == "lastUsedAt" || key == "revokedAt" {
					if value != nil {
						item[key] = "generated-time"
					}
				} else {
					normalize(value)
				}
			}
		case []any:
			for _, value := range item {
				normalize(value)
			}
		}
	}
	normalize(result)
	return result
}

func scaleP21M3PointDifferential(t *testing.T, operations []scaleP21M3PointOperation) {
	t.Helper()
	t.Setenv("FLOW_BOUNDED_METADATA", "off")
	t.Setenv("FLOW_RECORD_HYDRATION", "on")
	t.Setenv("FLOW_RECORD_JOURNAL", "on")
	for _, repo := range scaleP03ServerTestStores(t) {
		f := scaleP03Fixture(t, repo)
		workspace := f.data.Workspace.URLKey
		principals := scaleP21M3Principals(t, f)
		foreign, err := repo.CreateWorkspace(store.ContextWithActor(t.Context(), f.data.Viewer), "M3 foreign", idgen.New("m3-point-foreign-"), "us")
		if err != nil {
			t.Fatal(err)
		}
		f.resources.workspaces = append(f.resources.workspaces, foreign.Workspace.URLKey)
		probe, err := repo.BoundedMetadataViewForTesting(t.Context())
		if err != nil {
			t.Fatal(err)
		}
		unrelated := scaleP21M3Fingerprint(t, probe, workspace, "projects")
		for _, operation := range operations {
			for _, principal := range principals {
				for _, credential := range scaleP21M3Credentials() {
					t.Run(operation.name+"/"+principal.name+"/"+credential.name, func(t *testing.T) {
						for _, missing := range []bool{false, true} {
							var responses, effects, events, audits []any
							for _, current := range []*store.SQLiteStore{repo, probe} {
								if err := repo.ReloadWorkspace(t.Context(), workspace); err != nil {
									t.Fatal(err)
								}
								if err := repo.MutateWorkspace(t.Context(), workspace, "scale_p21.reset", "", nil, func(data *domain.Bootstrap) error {
									operation.seed(data, principal.user)
									return nil
								}); err != nil {
									t.Fatal(err)
								}
								if err := probe.RefreshInstalledMetadataViewForTesting(t.Context(), repo, workspace); err != nil {
									t.Fatal(err)
								}
								var webhook domain.DomainEvent
								var realtime domain.RealtimeEvent
								current.SetWebhookSink(func(_ string, event domain.DomainEvent) { webhook = event })
								current.SetRealtimeSink(func(_ string, event domain.RealtimeEvent) { realtime = event })
								r := scaleP21M3Request(workspace, principal.user, credential.key, operation.body)
								id := operation.id
								if missing {
									id += "-missing"
								}
								r.SetPathValue("id", id)
								w := httptest.NewRecorder()
								otherBefore, err := probe.ReadCanonicalRecords(t.Context(), workspace, operation.otherKeys, "detail")
								if err != nil {
									t.Fatal(err)
								}
								started := time.Now().UTC()
								scaleP21M3Call(&server{store: current}, w, r, operation.handler)
								baseline := current == repo && principal.name == "admin-private-outsider" && credential.name == "session" && !missing
								if baseline {
									switch {
									case strings.Contains(operation.name, "invalid"):
										if w.Code != http.StatusBadRequest {
											t.Fatalf("invalid fixture status=%d", w.Code)
										}
									case operation.name == "other-push-subscription":
										if w.Code != http.StatusNotFound {
											t.Fatalf("foreign subscription fixture status=%d", w.Code)
										}
									default:
										if w.Code < 200 || w.Code >= 300 {
											t.Fatalf("legacy fixture did not succeed: status=%d body=%s", w.Code, w.Body.String())
										}
									}
								}
								otherAfter, err := probe.ReadCanonicalRecords(t.Context(), workspace, operation.otherKeys, "detail")
								if err != nil || !reflect.DeepEqual(otherBefore, otherAfter) {
									t.Fatalf("unrelated canonical records changed: %v", err)
								}
								responses = append(responses, []any{w.Code, scaleP21M3PointJSON(t, scaleP21M3JSON(t, w.Body.Bytes()))})
								keys := []store.RecordKey{{Kind: operation.kind, ID: operation.id}}
								if operation.readKeys != nil {
									keys = operation.readKeys(principal.user)
								}
								scope := store.MetadataRecordScope{Read: keys}
								if operation.kind == "workspaceSettings" {
									scope = store.MetadataRecordScope{Fields: []string{"workspaceSettings"}}
								}
								hydrated, err := probe.HydrateWorkspaceMetadata(t.Context(), workspace, scope)
								data := hydrated.Data
								if err != nil {
									t.Fatalf("persisted record: %v", err)
								}
								if operation.kind == "apiKeys" && w.Code == http.StatusNoContent && !missing {
									if len(data.APIKeys) != 1 || data.APIKeys[0].RevokedAt == nil || data.APIKeys[0].RevokedAt.Before(started) || data.APIKeys[0].RevokedAt.After(time.Now().UTC()) {
										t.Fatal("key revocation did not persist the operation's live timestamp")
									}
								}
								if baseline && operation.name == "oauth-integration-error" && (len(data.IntegrationConnections) != 1 || data.IntegrationConnections[0].LastError != "after") {
									t.Fatal("legacy error updater did not change its target")
								}
								if baseline && operation.name == "export-completion" && (len(data.ExportJobs) != 1 || data.ExportJobs[0].Status != "completed" || data.ExportJobs[0].CompletedAt == nil) {
									t.Fatal("legacy export completion did not change its target")
								}
								effects = append(effects, scaleP21M3PointJSON(t, data))
								events = append(events, []any{
									webhook.Type, webhook.AggregateID, scaleP21M3PointJSON(t, webhook.Payload), scaleP21M3PointJSON(t, webhook.PreviousValues),
									realtime.Type, scaleP21M3PointJSON(t, realtime.Payload),
								})
								entries, err := repo.ListAuditEntries(t.Context(), f.data.Workspace.ID, store.AuditQuery{Since: started})
								if err != nil {
									t.Fatal(err)
								}
								if baseline && (operation.name == "personal-connection-audit" || operation.name == "coding-mcp-audit") && len(entries) != 1 {
									t.Fatalf("legacy audit producer wrote %d entries", len(entries))
								}
								for index := range entries {
									if credential.key != nil && credential.key.TeamRestriction == "all" && operation.name != "coding-mcp-audit" && operation.name != "export-completion" {
										if entries[index].BotActor == nil || entries[index].BotActor.ID != "m3-via" || entries[index].BotActor.OnBehalfOfID != principal.user.ID {
											t.Fatal("request actor attribution was lost")
										}
									}
									entries[index].ID, entries[index].Hash = "", ""
									entries[index].Seq = 0
									entries[index].CreatedAt = time.Time{}
								}
								audits = append(audits, entries)
							}
							if !reflect.DeepEqual(responses[0], responses[1]) || !reflect.DeepEqual(effects[0], effects[1]) || !reflect.DeepEqual(events[0], events[1]) || !reflect.DeepEqual(audits[0], audits[1]) {
								t.Fatalf("missing=%t responses=%v effects=%v events=%v audits=%v", missing, responses, effects, events, audits)
							}
						}
					})
				}
			}
		}
		member := principals[len(principals)-1].user
		for _, phase := range []string{"cross-workspace", "missing-workspace", "queued-revocation", "replay-revocation"} {
			key := workspace
			switch phase {
			case "cross-workspace":
				key = foreign.Workspace.URLKey
			case "missing-workspace":
				key = "m3-missing-" + foreign.Workspace.URLKey
			case "queued-revocation":
				if err := repo.SuspendMember(t.Context(), f.data.Workspace.ID, member.ID); err != nil {
					t.Fatal(err)
				}
			}
			for _, credential := range scaleP21M3Credentials() {
				for _, operation := range operations {
					var responses []any
					for _, current := range []*store.SQLiteStore{repo, probe} {
						if phase != "missing-workspace" {
							if err := repo.ReloadWorkspace(t.Context(), key); err != nil {
								t.Fatal(err)
							}
							if err := repo.MutateWorkspace(t.Context(), key, "scale_p21.reset", "", nil, func(data *domain.Bootstrap) error {
								operation.seed(data, f.data.Viewer)
								return nil
							}); err != nil {
								t.Fatal(err)
							}
						}
						r := scaleP21M3Request(key, member, credential.key, operation.body)
						r.SetPathValue("id", operation.id)
						w := httptest.NewRecorder()
						scaleP21M3Call(&server{store: current}, w, r, operation.handler)
						responses = append(responses, []any{w.Code, scaleP21M3PointJSON(t, scaleP21M3JSON(t, w.Body.Bytes()))})
					}
					if !reflect.DeepEqual(responses[0], responses[1]) {
						t.Fatalf("%s/%s/%s response differs: %v", phase, operation.name, credential.name, responses)
					}
				}
			}
		}
		if probe.WorkspaceMetadataDecodes() != 0 {
			t.Fatal("point handlers decoded full metadata")
		}
		if scaleP21M3Fingerprint(t, probe, workspace, "projects") != unrelated {
			t.Fatal("point handlers changed unrelated canonical bodies")
		}
	}
}

func TestScaleP21M3AdvancedPointDifferential(t *testing.T) {
	scaleP21M3PointDifferential(t, []scaleP21M3PointOperation{
		{
			name: "project-update-settings", kind: "settings", id: "projectUpdates", body: `{"cadenceDays":14}`,
			seed: func(data *domain.Bootstrap, _ domain.User) {
				data.Settings["projectUpdates"] = map[string]any{"cadenceDays": 7, "retained": "keep"}
			},
			handler: (*server).updateProjectUpdateSettings,
		},
		{
			name: "sla-settings", kind: "settings", id: "sla", body: `{"enabled":true,"workWeek":"sunThu"}`,
			seed: func(data *domain.Bootstrap, _ domain.User) {
				data.Settings["sla"] = map[string]any{"enabled": false, "workWeek": "monFri"}
			},
			handler: (*server).updateSLASettings,
		},
		{
			name: "favorite-folder", kind: "favoriteFolders", id: "m3-folder", body: `{"name":"After","position":4}`,
			seed: func(data *domain.Bootstrap, actor domain.User) {
				data.FavoriteFolders = []domain.FavoriteFolder{
					{ID: "m3-folder", UserID: actor.ID, Name: "Before", CreatedAt: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)},
					{ID: "m3-unrelated-folder", UserID: "another-user", Name: strings.Repeat("unrelated ", 10)},
				}
			},
			handler:   (*server).updateFavoriteFolder,
			otherKeys: []store.RecordKey{{Kind: "favoriteFolders", ID: "m3-unrelated-folder"}},
		},
		{
			name: "export-completion", kind: "exportJobs", id: "m3-export", body: `{}`,
			seed: func(data *domain.Bootstrap, actor domain.User) {
				data.Viewer = actor
				data.ExportJobs = []domain.ExportJob{
					{ID: "m3-export", UserID: actor.ID, Format: "json", Status: "queued", CreatedAt: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)},
					{ID: "m3-other-export", UserID: actor.ID, Format: "csv", Status: "failed", Error: "retained"},
				}
			},
			handler: func(s *server, w http.ResponseWriter, r *http.Request) {
				s.completeExport(workspaceKey(r), r.PathValue("id"))
				w.WriteHeader(http.StatusNoContent)
			},
			otherKeys: []store.RecordKey{{Kind: "exportJobs", ID: "m3-other-export"}},
		},
	})
}
