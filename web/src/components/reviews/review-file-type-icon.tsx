/** The glyph for a path's file type (by extension), else the generic file glyph. */
export function fileTypeGlyph(path: string): Glyph {
  const name = path.split("/").at(-1) ?? path;
  const extension = name.includes(".") ? name.split(".").at(-1)!.toLowerCase() : "";
  return BY_EXTENSION[extension] ?? FILE;
}

/** A file's type glyph (16px, greyscale like the rest of the file header). */
export function ReviewFileTypeIcon({ path, className }: { path: string; className?: string }) {
  const glyph = fileTypeGlyph(path);
  return (
    <svg className={className} width="16" height="16" viewBox={glyph.viewBox} aria-hidden="true" data-file-type-icon="">
      {glyph.paths.map(([fill, d], index) => <path key={index} fill={fill} d={d} />)}
    </svg>
  );
}

