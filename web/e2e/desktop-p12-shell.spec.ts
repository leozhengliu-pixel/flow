test('issue keyboard actions use the actual property controls and persist assignment', async ({ page, request, context, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const boot = await (await request.get('/api/bootstrap', { headers })).json() as BootstrapData
  const created = await request.post('/api/issues', { headers, data: { title: '[audit] Keyboard issue', teamId: boot.teams[0].id, stateId: 'state_todo' } })
  expect(created.status()).toBe(201)
  const issue = await created.json() as { id: string; identifier: string }
  await page.goto(`/${workspaceKey}/issue/${issue.identifier}`)
  await expect(page.getByRole('textbox', { name: 'Issue title', exact: true })).toBeVisible()
  await page.locator('main').click({ position: { x: 600, y: 50 } })
  await page.keyboard.press('p')
  const priority = page.getByRole('dialog', { name: 'Change Priority', exact: true })
  await expect(priority).toBeVisible()
  const savedPriority = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().endsWith(`/api/issues/${issue.id}`))
  await priority.getByRole('option', { name: /^Urgent/ }).click()
  expect((await (await savedPriority).json() as { priority: number }).priority).toBe(1)
  await expect(priority).toHaveCount(0)
  await page.keyboard.press('s')
  await expect(page.getByRole('dialog', { name: 'Change Status', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Change Status', exact: true })).toHaveCount(0)
  await page.keyboard.press('a')
  await expect(page.getByRole('dialog', { name: 'Change Assignee', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Change Assignee', exact: true })).toHaveCount(0)
  const assigned = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().endsWith(`/api/issues/${issue.id}`))
  await page.keyboard.press('i')
  expect((await (await assigned).json() as { assignee?: { id: string } }).assignee?.id).toBe(boot.viewer.id)
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.keyboard.press('ControlOrMeta+Period')
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(issue.identifier)
  // O then P must not open Priority when the issue owns P.
  await page.keyboard.press('o')
  await page.keyboard.press('p')
  await expect(page.locator('[cmdk-root]')).toBeVisible()
  await expect(priority).toHaveCount(0)
})

test('command queries, expanded shortcut help and performance reporting remain functional', async ({ page, context, workspaceKey }) => {
  await page.goto(`/${workspaceKey}/agent`)
  await expect(page.locator('.sidebar-compose')).toBeVisible()
  await page.locator('main > header').click({ position: { x: 300, y: 20 } })
  await page.keyboard.press('ControlOrMeta+k')
  const palette = page.locator('[cmdk-root]')
  await palette.locator('[cmdk-input]').fill('pro')
  await expect(palette.getByRole('option', { name: /^Create new project…/ })).toBeVisible()
  await expect(palette.getByRole('option', { name: /^Open project…/ })).toBeVisible()
  await page.waitForTimeout(500)
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/shell-commands.png`, animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.keyboard.press('ControlOrMeta+/')
  const help = page.locator('.sidebar-shortcuts-dialog')
  await expect(help.getByText('Save or submit', { exact: true })).toBeVisible()
  await help.getByRole('textbox', { name: 'Search shortcuts', exact: true }).fill('Assign issue to user')
  await expect(help.getByText('Assign issue to user', { exact: true })).toBeVisible()
  await page.waitForTimeout(500)
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/shell-shortcuts.png`, animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(help).toHaveCount(0)
  await page.locator('main > header').click({ position: { x: 300, y: 20 } })
  await context.route('https://github.com/leozhengliu-pixel/flow/issues/new**', route => route.fulfill({ contentType: 'text/html', body: '<title>Performance report</title>' }))
  await page.keyboard.press('ControlOrMeta+k')
  await palette.locator('[cmdk-input]').fill('Report performance')
  const opened = context.waitForEvent('page')
  await palette.getByRole('option', { name: 'Report performance problem', exact: true }).click()
  const report = await opened
  await report.waitForLoadState('domcontentloaded')
  expect(new URL(report.url()).searchParams.get('title')).toBe('Report performance problem')
  await report.close()
  await expect(page).toHaveURL(new RegExp(`/${workspaceKey}/agent$`))
})

test('matching team capabilities expose triage and cycle links, with working cycle navigation', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const boot = await (await request.get('/api/bootstrap', { headers })).json() as BootstrapData
  const team = boot.teams[0]
  expect((await request.patch(`/api/teams/${team.id}/settings`, { headers, data: { triageEnabled: true } })).ok()).toBeTruthy()
  expect((await request.patch(`/api/teams/${team.id}/cycle-settings`, { headers, data: { enabled: true, durationWeeks: 1, upcomingCount: 2, autoCreate: true } })).ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/team/${team.key}/all`)
  const sidebar = page.locator('.sidebar')
  await expect(sidebar.getByRole('link', { name: 'Triage', exact: true })).toBeVisible()
  await expect(sidebar.getByRole('link', { name: 'Current', exact: true })).toBeVisible()
  await expect(sidebar.getByRole('link', { name: 'Upcoming', exact: true })).toBeVisible()
  await page.locator('main > header').click({ position: { x: 300, y: 20 } })
  await page.keyboard.press('g')
  await page.keyboard.press('v')
  await expect(page).toHaveURL(new RegExp(`/team/${team.key}/cycle/`))
  await page.keyboard.press('g')
  await page.keyboard.press('w')
  await expect(page).toHaveURL(new RegExp(`/team/${team.key}/cycle/upcoming$`))
  await page.keyboard.press('o')
  await page.keyboard.press('c')
  await expect(page.locator('[cmdk-root]')).toBeVisible()
  await expect(page.locator('[cmdk-root] [cmdk-item]').first()).toBeVisible()
})
