import { test, expect } from './issue-list-fixture'

test.skip(({ isMobile }) => isMobile, 'Desktop issue command picker')
test.use({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' })

test('O then I opens a searchable issue picker, Enter navigates, and Help lists the shortcut', async ({ page, workspaceKey, issueList }) => {
  await page.goto(issueList.route)
  await expect(page.locator(`[data-issue-row-id="${issueList.issues[0].id}"]`)).toBeVisible()
  await page.keyboard.press('o')
  await page.keyboard.press('i')
  const dialog = page.getByRole('dialog', { name: 'Command menu' })
  await expect(dialog).toBeVisible()
  const input = dialog.getByRole('combobox')
  await expect(input).toHaveAttribute('placeholder', 'Open issue…')
  await input.fill(issueList.issues[1].identifier)
  const result = dialog.getByRole('option').filter({ hasText: issueList.issues[1].title })
  await expect(result).toBeVisible()
  await input.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('textbox', { name: 'Issue title', exact: true })).toHaveText(issueList.issues[1].title)
  await expect(page).toHaveURL(new RegExp(`/${workspaceKey}/issue/${issueList.issues[1].identifier}`))
  await page.keyboard.press('o')
  await page.keyboard.press('i')
  await expect(input).toHaveValue('')
  await input.fill('no such issue 9fd17')
  await expect(dialog.getByText('No results found.', { exact: true })).toBeVisible()
  await input.press('Escape')
  await expect(dialog.getByRole('option', { name: /Open issue…/ })).toBeVisible()
  await input.press('Escape')
  await page.keyboard.press('Control+/')
  const help = page.getByRole('dialog', { name: 'Keyboard Shortcuts' })
  await expect(help).toBeVisible()
  await help.getByRole('textbox', { name: 'Search shortcuts' }).fill('Open issue')
  await expect(help.getByText('Open issue', { exact: true })).toBeVisible()
  await expect(help.locator('dd kbd')).toHaveText(['O', 'I'])
})
