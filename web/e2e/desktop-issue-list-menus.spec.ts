test('shows every display property and footer, persists defaults, and filters sub-team issues', async ({ page, request, workspaceKey, issueList }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const parent = issueList.data.teams[0]
  const childResponse = await request.post(`/api/workspaces/${workspaceKey}/teams`, { headers, data: { name: '[audit] Sub-team', key: 'SUB', parentTeamId: parent.id } })
  expect(childResponse.status()).toBe(201)
  const child = await childResponse.json() as Team
  const created = await request.post('/api/issues', { headers, data: { title: '[audit] Sub-team issue', teamId: child.id } })
  expect(created.status()).toBe(201)
  const childIssue = await created.json() as { id: string }
  await page.goto(issueList.route)
  const childRow = page.locator(`[data-issue-row-id="${childIssue.id}"]`)
  await expect(childRow).toBeVisible()
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Display options', exact: true })
  await expect(panel.getByRole('checkbox', { name: 'Show sub-team issues', exact: true })).toBeChecked()
  await panel.getByRole('checkbox', { name: 'Show sub-team issues', exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await expect(childRow).toHaveCount(0)
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  await panel.getByRole('tab', { name: 'Board', exact: true }).click()
  await expect(panel.getByRole('tab', { name: 'Board', exact: true })).toHaveCSS('padding', '6px 8px')
  await expect(panel.getByRole('combobox',{name:'Grouping',exact:true})).toHaveCSS('width','160px')
  await expect(panel.getByText('Columns', { exact: true })).toBeVisible()
  await expect(panel.getByText('Rows', { exact: true })).toBeVisible()
  const geometry = await panel.evaluate(e => {
    const rect = e.getBoundingClientRect()
    const footer = e.querySelector('footer')!.getBoundingClientRect()
    const chips = [...e.querySelectorAll('[data-property]')].map(chip => chip.getBoundingClientRect())
    return { scroll: e.scrollHeight - e.clientHeight, bottom: rect.bottom, footer: footer.top, lastChip: Math.max(...chips.map(chip => chip.bottom)) }
  })
  expect(geometry.scroll).toBeLessThanOrEqual(1)
  expect(geometry.bottom).toBeLessThan(900)
  expect(geometry.lastChip).toBeLessThan(geometry.footer)
  // The menu lists only properties the issues can have: this workspace has no SLAs, release pipelines or activity tab.
  for (const property of ['SLA', 'Release', 'My activity date']) await expect(panel.getByRole('button', { name: property, exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(panel.getByRole('checkbox', { name: 'Show sub-team issues', exact: true })).toBeChecked()
  await panel.getByRole('tab', { name: 'Board', exact: true }).click()
  const save = page.waitForResponse(response => response.request().method() === 'PATCH' && new URL(response.url()).pathname === `/api/teams/${parent.id}/settings`)
  await panel.getByRole('button', { name: 'Set default for everyone', exact: true }).click()
  expect((await save).ok()).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('list', { name: 'Issue board', exact: true })).toBeVisible()
})

