test('new-view title stays editable while its bright fallback and full-width description match desktop', async ({ page, workspaceKey, issueList }) => {
  await page.goto(`/${workspaceKey}/views/issues/new`)
  const name = page.getByRole('textbox', { name: 'View name', exact: true })
  await expect(name).toHaveValue('')
  await expect(name).toHaveAttribute('placeholder', 'All issues')
  await expect(page.locator('[data-content-view-breadcrumb] [data-current] span').last()).toHaveCSS('color', 'lch(90.451 1.2 272)')
  await expect(page.locator('[data-content-view-header] [data-header-row]')).toHaveCSS('padding-left', '8px')
  await expect(page.getByRole('button', { name: 'Choose icon', exact: true })).toHaveCSS('padding', '0px 8px')
  await expect(page.getByRole('button', { name: 'Create view', exact: true })).toHaveCSS('background-color', 'lch(47.918 59.303 288.421)')
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toHaveCSS('color', 'lch(90.826 1.425 272)')
  await expect(page.getByRole('button', { name: /^Save to Personal/ })).toHaveCSS('padding', '0px 8px 0px 6px')
  await expect(page.locator('[class*="saveActions"]')).toHaveCSS('gap', '6px')
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/desktop-new-view.png`, animations: 'disabled' })
  const metrics = await name.evaluate(input => {
    const description = document.querySelector('input[aria-label="Description (optional)"]')!
    const field = input.getBoundingClientRect(), desc = description.getBoundingClientRect()
    const header = input.parentElement!.parentElement!.getBoundingClientRect()
    const style = getComputedStyle(input.parentElement!.parentElement!)
    return { name: [field.x, field.y], description: [desc.x, desc.y, desc.width], header: [header.x, header.y], padding: [parseFloat(style.paddingLeft), parseFloat(style.paddingTop)], placeholder: getComputedStyle(input, '::placeholder').color, bright: getComputedStyle(input).getPropertyValue('--bright').trim() }
  })
  expect(metrics.name[0] - metrics.header[0]).toBe(metrics.padding[0] + 28 + 5)
  expect(metrics.name[1] - metrics.header[1]).toBe(metrics.padding[1] + 2)
  expect(metrics.description[0] - metrics.name[0]).toBe(1)
  expect(metrics.description[1] - metrics.name[1]).toBe(32)
  expect(metrics.description[2]).toBeGreaterThan(1100)
  expect(metrics.placeholder).not.toContain('36.975')
  await name.fill('[audit] Desktop view')
  await expect(page.locator('[data-content-view-breadcrumb] [data-current]')).toHaveText('[audit] Desktop view')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/${workspaceKey}/views/issues$`))
  expect(issueList.issues).toHaveLength(3)
})

