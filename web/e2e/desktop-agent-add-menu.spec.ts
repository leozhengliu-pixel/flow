test('keys: arrows move and wrap, Right opens the skills, Left goes back, Enter puts the skill in the message, Escape returns focus to "+"', async ({ page, workspaceKey }) => {
  await openAgent(page, workspaceKey, 4)
  const plus = page.locator('[data-agent-add]').first()
  await plus.click()
  const menu = page.getByRole('menu', { name: 'Add files and more', exact: true })
  await settled(menu)
  const focusedText = () => page.evaluate(() => document.activeElement?.textContent ?? '')
  const press = async (key: string, expected: string) => {
    await page.keyboard.press(key)
    await expect.poll(focusedText).toContain(expected)
  }
  await press('ArrowDown', 'File')
  await press('ArrowDown', 'Skill')
  await press('ArrowDown', 'File')
  await press('ArrowUp', 'Skill')
  await page.keyboard.press('ArrowRight')
  const sub = page.getByRole('menu', { name: 'Skill', exact: true })
  await settled(sub)
  await expect(sub).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(sub).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(plus).toBeFocused()
  // Enter on a skill closes the menu and leaves its chip in the composer, with focus there.
  await plus.click()
  await settled(menu)
  await press('ArrowDown', 'File')
  await press('ArrowDown', 'Skill')
  await page.keyboard.press('ArrowRight')
  await expect(sub).toBeVisible()
  await expect.poll(focusedText).toContain('Flow parity skill with a very long name')
  await page.keyboard.press('Enter')
  await expect(menu).toBeHidden()
  const chip = page.locator('[role=textbox] [data-mention-type="skill"]')
  await expect(chip).toHaveCount(1)
  await expect(chip).toHaveAttribute('data-mention-id', 'skill-4')
  await expect(page.locator('[role=textbox]').first()).toBeFocused()
})

test('"/" opens a 227px menu under the line: the Skills section (newest four), a hairline, Insert media and Attach files', async ({ page, workspaceKey }) => {
  await openAgent(page, workspaceKey, 4)
  const editor = page.locator('[role=textbox]').first()
  await editor.click()
  await page.keyboard.type('/')
  const menu = page.getByRole('listbox', { name: 'Insert block' })
  await settled(menu)
  const at = await box(editor)
  const surface = await box(menu)
  expect(surface.width).toBe(227)
  expect([surface.x, surface.y]).toEqual([at.x - 4, at.y + 24 + 4])
  await expect(menu).toHaveCSS('border-radius', '10px')
  await expect(menu).toHaveCSS('background-color', 'lch(16.433 1.3 272)')
  await expect(menu).toHaveCSS('border-top-color', 'lch(29.393 2.38 272)')
  const heading = menu.getByText('Skills', { exact: true })
  const head = await box(heading.locator('..'))
  expect([head.x, head.y, head.width, head.height]).toEqual([surface.x + 0.5, surface.y + 4.5, 226, 28])
  await expect(heading).toHaveCSS('color', 'lch(66.215 1.65 272)')
  expect((await box(heading)).x).toBe(surface.x + 0.5 + 14)
  const rows = menu.getByRole('option')
  await expect(rows).toHaveText([...SKILLS.map(([, name]) => name).reverse(), 'Insert media…', /^Attach files…/])
  const boxes = await Promise.all((await rows.all()).map(box))
  expect(boxes.map(row => row.height)).toEqual([34, 34, 34, 34, 34, 34])
  expect(boxes[0].y).toBe(head.y + 28)
  // The hairline between groups: 5px above it, 5px below.
  const separator = await box(menu.getByRole('separator'))
  expect([separator.height, separator.y - (boxes[3].y + 34), boxes[4].y - (separator.y + separator.height)]).toEqual([0.5, 5, 5])
  // Skills have no icon (the name starts 14px in); commands have a 20px icon slot and the name 42px in.
  expect(await rows.first().evaluate(row => row.querySelector('svg') === null)).toBe(true)
  const nameAt = async (row: Locator) => (await box(row.locator('[class*=label]'))).x
  expect(await nameAt(rows.first())).toBe(boxes[0].x + 14)
  expect(await nameAt(rows.nth(4))).toBe(boxes[4].x + 42)
  expect((await box(rows.nth(5).locator('[class*=icon]'))).width).toBe(20)
  expect(await rows.nth(5).locator('kbd').allTextContents()).toEqual(['⌘', '⇧', 'U'])
  // The first row is the focused one.
  expect(await rows.first().evaluate(row => getComputedStyle(row, '::before').backgroundColor)).toBe('lch(24.532 1.75 272)')
  await expect(rows.first()).toHaveAttribute('aria-selected', 'true')
  await expect(rows.nth(1)).toHaveAttribute('aria-selected', 'false')
})

