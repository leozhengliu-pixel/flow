import { expect } from '@playwright/test'
import { test } from './workspace-fixture'

test.use({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, timezoneId: 'Pacific/Auckland' })

test('sidebar issue shortcuts appear on hover and focus without navigating', async ({ page, workspaceKey }) => {
  await page.goto(`/${workspaceKey}/agent`)
  const link = page.locator('.sidebar-team a').filter({ hasText: /^Issues$/ }).first()
  await link.hover()
  await expect(page.locator('.sidebar-issues-tooltip')).toBeVisible()
  const tooltip = page.locator('.sidebar-issues-tooltip')
  await expect(tooltip).toHaveCSS('font-size', '11px')
  await expect(tooltip).toHaveCSS('padding', '5px 8px')
  await expect(tooltip.locator('.sidebar-issues-shortcut')).toHaveCount(3)
  await expect(tooltip.locator('kbd')).toHaveText(['G', 'E', 'G', 'A', 'G', 'B'])
  await expect(tooltip.locator('.sidebar-issues-shortcuts')).toHaveCSS('gap', '4px')
  await page.waitForTimeout(200)
  const trigger = (await link.boundingBox())!
  expect(trigger.height).toBe(28)
  const card = (await tooltip.boundingBox())!
  expect(card.x - trigger.x - trigger.width).toBe(8)
  await page.mouse.move(700, 100)
  await expect(tooltip).not.toBeVisible()
  await link.focus()
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tooltip).not.toBeVisible()
  await expect(link).toBeFocused()
  await expect(page).toHaveURL(new RegExp(`/${workspaceKey}/agent$`))
})

test('the same person card works in rows, issue details and board cards', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  expect((await request.patch('/api/account/settings', { headers, data: { timezone: 'Pacific/Auckland' } })).ok()).toBe(true)
  await page.clock.setFixedTime(new Date('2026-11-04T12:00:00Z'))
  const data = await (await request.get('/api/bootstrap', { headers })).json()
  const team = data.teams[0]
  const created = await request.post('/api/issues', { headers, data: { title: 'Assignee hover fixture', teamId: team.id, stateId: 'state_todo', assigneeId: data.viewer.id } })
  expect(created.status()).toBe(201)
  const issue = await created.json()
  const route = `/${workspaceKey}/team/${team.key}/all`
  await page.goto(route)
  const trigger = page.locator('[data-property="assignee"]').first()
  await trigger.hover()
  const card = page.locator('.assignee-person-surface')
  await expect(card).toBeVisible()
  await expect(card.locator('header .avatar')).toHaveCSS('width', '32px')
  await expect(card.locator('strong')).toHaveText(data.viewer.displayName)
  await expect(card.getByRole('link', { name: team.name, exact: true })).toHaveAttribute('href', `/${workspaceKey}/team/${team.key}/overview`)
  await expect(card).not.toContainText('Offline')
  await expect(card).toContainText('1:00 AM')
  await expect(card).toContainText('local time')
  const profile = card.getByRole('link', { name: data.viewer.displayName, exact: true })
  const profilePath = await profile.getAttribute('href')
  await profile.hover()
  await expect(card).toBeVisible()
  await profile.click()
  expect(new URL(page.url()).pathname).toBe(profilePath)
  await page.goto(route)
  await trigger.hover()
  await expect(card).toBeVisible()
  await page.mouse.move(700, 100)
  await expect(card).not.toBeVisible()
  await page.goto(`/${workspaceKey}/issue/${issue.identifier}`)
  await page.locator('.issue-assignee-property [data-property="assignee"]').hover()
  await expect(card).toBeVisible()
  await expect(card.locator('strong')).toHaveText(data.viewer.displayName)
  await page.evaluate(({ workspaceKey, teamId }) => localStorage.setItem(`${workspaceKey}:issue-explorer:team:${teamId}:all:display`, JSON.stringify({ layout: 'board', grouping: 'status', properties: ['assignee', 'id'], showEmptyGroups: false })), { workspaceKey, teamId: team.id })
  await page.goto(route)
  await expect(page.locator('[data-board-card-title]')).toHaveText('Assignee hover fixture')
  await page.locator('[data-property="assignee"]').first().hover()
  await expect(card).toBeVisible()
  await expect(card.locator('strong')).toHaveText(data.viewer.displayName)
  await page.locator('[data-property="assignee"]').first().click()
  await expect(card).not.toBeVisible()
  await expect(page.getByRole('listbox', { name: 'Assignee', exact: true })).toBeVisible()
})

test('a favorited initiative names the removal action without changing it on hover', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const created = await request.post('/api/initiatives', { headers, data: { name: 'Favorite hover fixture' } })
  expect(created.status()).toBe(201)
  const initiative = await created.json()
  expect((await request.patch(`/api/initiatives/${initiative.id}`, { headers, data: { favorite: true } })).ok()).toBe(true)
  await page.goto(`/${workspaceKey}/initiative/${initiative.slugId || initiative.id}/overview`)
  const star = page.getByRole('switch', { name: 'Remove from favorites' })
  await expect(star).toHaveAttribute('aria-checked', 'true')
  await star.hover()
  await expect(page.getByRole('tooltip')).toHaveText('Remove from favorites')
  await expect(star).toHaveAttribute('aria-checked', 'true')
})
