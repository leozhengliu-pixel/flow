import { test, expect } from './issue-list-fixture'

test.skip(({ isMobile }) => isMobile, 'Desktop board metrics')
test.use({ viewport: { width: 1440, height: 900 } })

test('hides and restores columns, remembers visibility, and keeps the hidden panel at the right edge', async ({ page, issueList }) => {
  await page.goto(issueList.route)
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  await page.getByRole('tab', { name: 'Board', exact: true }).click()
  await page.keyboard.press('Escape')
  const column = page.locator('[data-board-column]').filter({ has: page.locator('[data-board-column-title]', { hasText: 'Todo' }) })
  await column.getByRole('button', { name: 'Open menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Hide column', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Hidden columns' })
  await expect(panel).toBeVisible()
  await expect(column).toHaveCount(0)
  const header = await panel.locator('[data-board-hidden-header-strip]').boundingBox()
  const row = await panel.locator('[data-board-hidden-status]').first().boundingBox()
  expect(header?.width).toBe(338)
  expect(header?.height).toBe(50)
  expect(row?.width).toBe(338)
  expect(row?.height).toBe(37)
  expect(header!.x).toBeCloseTo(1081, 0)
  await page.reload()
  await expect(panel.getByRole('button', { name: 'Todo 3', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'Collapse group', exact: true }).click()
  await expect(panel.locator('[data-board-hidden-status]')).toHaveCount(0)
  await panel.getByRole('button', { name: 'Expand group', exact: true }).click()
  await panel.getByRole('button', { name: 'Todo 3', exact: true }).click()
  await expect(column).toBeVisible()
  await page.reload()
  await expect(column).toBeVisible()
})
