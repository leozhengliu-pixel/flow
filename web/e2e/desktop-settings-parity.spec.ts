test('workspace announcements save in the throwaway workspace and reopen after reload', async ({ page, workspaceKey }) => {
  await page.goto(`/${workspaceKey}/settings/workspace`)
  await page.getByRole('button', { name: 'Configure announcements' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox', { name: 'Enable announcements' }).check()
  await dialog.getByRole('textbox', { name: 'Announcement title' }).fill('[audit] Team news')
  await dialog.getByRole('textbox', { name: 'Announcement message' }).fill('[audit] Read the handbook')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Configure announcements' }).click()
  await expect(dialog.getByRole('textbox', { name: 'Announcement title' })).toHaveValue('[audit] Team news')
  await expect(dialog.getByRole('checkbox', { name: 'Enable announcements' })).toBeChecked()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await page.goto(`/${workspaceKey}/settings/api`)
  await expect(page.getByRole('link', { name: 'Docs' })).toHaveCount(3)
  for (const [label, y] of [['OAuth applications', 206.5], ['Webhooks', 381.5], ['API keys', 578.5]] as const) {
    const rect = await page.getByRole('heading', { name: label, exact: true }).boundingBox()
    expect(Math.abs(rect!.y - y)).toBeLessThanOrEqual(1)
  }
  await page.getByRole('main').getByRole('link', { name: 'Security & access', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/settings/account/security$'))
})
