test('desktop integrations separate installed services, discover, search, and retain both chat providers', async ({ page, workspaceKey }) => {
  await page.route('**/api/bootstrap', async route => {
    const response = await route.fetch()
    const data = await response.json()
    data.integrationConnections = [{ id: 'audit-gh', provider: 'github', status: 'connected', name: 'GitHub' }]
    await route.fulfill({ response, json: data })
  })
  await page.goto(`/${workspaceKey}/settings/integrations`)
  const enabled = page.locator('.desktop-enabled-card').first()
  await expect(enabled).toHaveText('GitHubEnabled')
  expect((await enabled.boundingBox())?.height).toBe(68)
  const search = page.getByRole('textbox', { name: 'Search integrations' })
  expect((await search.boundingBox())?.width).toBe(638)
  const tabs = page.getByRole('tablist', { name: 'Featured integrations' })
  await tabs.getByRole('tab', { name: 'Feishu' }).click()
  await expect(tabs.getByRole('tab', { name: 'Feishu' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Next integration' }).click()
  await expect(tabs.getByRole('tab', { name: 'Lark' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Previous integration' }).click()
  await expect(tabs.getByRole('tab', { name: 'Feishu' })).toHaveAttribute('aria-selected', 'true')
  await search.fill('lark')
  await expect(page.locator('.desktop-enabled').getByRole('button', { name: /GitHub/ })).toBeVisible()
  await expect(page.locator('.desktop-integration-catalog .desktop-enabled-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Lark Essentials' }).click()
  await expect(page).toHaveURL(new RegExp(`/settings/integrations/lark$`))
  await page.goto(`/${workspaceKey}/settings/integrations`)
  await page.getByRole('textbox', { name: 'Search integrations' }).fill('feishu')
  await page.getByRole('button', { name: 'Feishu Essentials' }).click()
  await expect(page).toHaveURL(new RegExp(`/settings/integrations/feishu$`))
})

test('teams sort by every column, expose member links, and show live overview values', async ({ page, request, workspaceKey }) => {
  const response = await request.post(`/api/workspaces/${workspaceKey}/teams`, { data: { name: '[audit] Zulu', key: 'ZUL' } })
  expect(response.status()).toBe(201)
  await page.goto(`/${workspaceKey}/settings/teams`)
  await expect(page.getByRole('button', { name: 'Create team', exact: true })).toBeVisible()
  for (const column of ['Description', 'Visibility', 'Members', 'Issues', 'Created', 'Name']) {
    const button = page.getByRole('button', { name: `Order by ${column}`, exact: true })
    await button.click()
    const before = await button.locator('..').getAttribute('aria-sort')
    await button.click()
    expect(await button.locator('..').getAttribute('aria-sort')).not.toBe(before)
  }
  const directory = page.locator('.settings-teams-row')
  const names = await directory.locator('strong').allTextContents()
  expect(names).toEqual([...names].sort((a, b) => b.localeCompare(a)))
  await page.goto(`/${workspaceKey}/settings/teams/ZUL`)
  await expect(page.getByText('Accessible to all workspace members')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Team overview', exact: true })).toBeVisible()
  expect((await page.locator('.team-overview-icon').first().boundingBox())?.width).toBe(32)
  await expect(page.locator('.team-overview-summary').first()).toHaveText('1 member')
  await page.getByRole('link', { name: /^Project labels/ }).click()
  await expect(page).toHaveURL(new RegExp('/teams/ZUL/project-labels$'))
})

