import { expect } from '@playwright/test'
import { test, bootstrap, createReview, preferences, capture } from './review-findings-fixture'

for (const width of [375, 390]) for (const theme of ['Light', 'Dark'] as const) for (const locale of ['en-US', 'zh-CN']) {
  test(`keeps phone breadcrumbs, activity and reviewer copy contained ${width} ${theme} ${locale}`, async ({ page, request, workspaceKey }) => {
    if (process.env.FLOW_REVIEW_SHOTS) test.setTimeout(90_000)
    await page.setViewportSize({ width, height: width === 375 ? 667 : 844 })
    await preferences(request, workspaceKey, theme, locale)
    const headers = { 'X-Workspace-Key': workspaceKey }, data = await bootstrap(request, workspaceKey)
    const parent = await (await request.post('/api/issues', { headers, data: { title: 'International infrastructure reliability program for all regional teams', teamId: data.teams[0].id, stateId: 'state_todo' } })).json()
    const childResponse = await request.post('/api/issues', { headers, data: { title: '中文 Review all outstanding launch dependencies', teamId: data.teams[0].id, stateId: 'state_todo', parentId: parent.id, assigneeId: data.viewer.id, labelIds: [data.labels[0].id] } })
    expect(childResponse.status()).toBe(201)
    const child = await childResponse.json()
    await page.goto(`/${workspaceKey}/my-issues/assigned`)
    const row = page.locator(`[data-issue-row-id="${child.id}"]`)
    await expect(row).toBeVisible()
    const pill = row.locator('[class*=badgeSlot]').first()
    await expect(pill).toBeVisible()
    const avatar = row.locator('[data-user-avatar]').first()
    expect((await pill.boundingBox())!.x + (await pill.boundingBox())!.width).toBeLessThanOrEqual((await avatar.boundingBox())!.x)
    const trail = row.locator('[class*=parentTrail]').first()
    await expect(trail).toBeVisible()
    expect((await trail.boundingBox())!.x + (await trail.boundingBox())!.width).toBeLessThanOrEqual((await pill.boundingBox())!.x)
    await capture(row, `phone-breadcrumb-${width}-${theme}-${locale}`)
    await createReview(request, workspaceKey)
    await page.goto(`/${workspaceKey}/review/github-1`)
    const addReviewer = page.locator('[data-mobile-property=reviewers] .is-muted > span')
    await expect(addReviewer).toHaveCSS('color', theme === 'Dark' ? 'lch(61.803 1.2 272)' : 'lch(37.776 1.25 282)')
    await capture(page.locator('.review-mobile-properties'), `review-properties-${width}-${theme}-${locale}`)
    const addReviewerButton = addReviewer.locator('..')
    await addReviewerButton.hover()
    await page.keyboard.press('Tab')
    await addReviewerButton.focus()
    expect(await addReviewerButton.evaluate(element => element.matches(':focus-visible'))).toBe(true)
    await capture(page.locator('.review-mobile-properties'), `review-properties-focus-${width}-${theme}-${locale}`)
    await addReviewerButton.click()
    await expect(page.getByRole('dialog').last()).toBeVisible()
    await page.keyboard.press('Escape')
    const projectResponse = await request.post('/api/projects', { headers, data: { name: 'Phone activity', teamIds: [data.teams[0].id] } })
    expect(projectResponse.status()).toBe(201)
    const project = await projectResponse.json()
    expect((await request.post(`/api/projects/${project.id}/comments`, { headers, data: { body: 'A project update card after an activity event.' } })).ok()).toBe(true)
    expect((await request.patch(`/api/projects/${project.id}`, { headers, data: { name: '中文 International infrastructure reliability program for all regional teams' } })).ok()).toBe(true)
    await page.goto(`/${workspaceKey}/project/${project.slugId}/activity`)
    const composer = page.locator('.project-activity__composer')
    await expect(composer).toBeVisible()
    const closeDetails = page.getByRole('button', { name: /Close project details|关闭项目详情/ })
    if (await closeDetails.count()) await closeDetails.click()
    await composer.getByRole('tab', { name: locale === 'zh-CN' ? '更新' : 'Update', exact: true }).click()
    await expect(composer).toHaveAttribute('data-mode', 'update')
    await expect(composer).toHaveCSS('padding-bottom', '0px')
    expect(await composer.evaluate(element => element.scrollHeight <= element.clientHeight)).toBe(true)
    await capture(composer, `project-composer-${width}-${theme}-${locale}`)
    await composer.locator('[contenteditable=true]').fill('中文 Project update covering launch readiness, cross-team dependencies, remaining risks, and the next milestones for the international infrastructure reliability program.')
    await expect(composer.locator('button.is-submit')).toBeEnabled()
    const composerBounds = (await composer.boundingBox())!, footerBounds = (await composer.locator('footer').boundingBox())!
    expect(footerBounds.y + footerBounds.height).toBeLessThanOrEqual(composerBounds.y + composerBounds.height)
    await capture(composer, `project-composer-filled-${width}-${theme}-${locale}`)
    const events = page.locator('.project-activity__event')
    await expect(events.first()).toBeVisible()
    expect(await events.evaluateAll(elements => elements.every(element => {
      const text = element.querySelector(':scope > span:last-child')
      return !text || text.getBoundingClientRect().bottom <= element.getBoundingClientRect().bottom
    }))).toBe(true)
    await capture(page.locator('.project-activity__feed'), `project-feed-${width}-${theme}-${locale}`)
  })
}
