  await expect(timeline.locator('.lp-project-timeline__bar')).toBeVisible()
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/desktop-project-timeline.png`, animations: 'disabled' })
