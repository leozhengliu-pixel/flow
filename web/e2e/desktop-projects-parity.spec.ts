test('shows persisted initiative updates with a docked, collapsible properties and activity rail', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const created = await request.post('/api/initiatives', { headers, data: { name: '[audit] Desktop initiative', status: 'active' } })
  expect(created.ok()).toBeTruthy()
  const initiative = await created.json() as Initiative
  const posted = await request.post(`/api/initiatives/${initiative.id}/updates`, { headers, data: { body: 'Delivery remains on schedule.', health: 'onTrack' } })
  expect(posted.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/initiative/${initiative.slugId}/overview`)
  const rail = page.locator('.li-detail-sidebar')
  await expect(rail).toBeVisible()
  const statusLabel = await rail.locator('dt').filter({ hasText: /^Status$/ }).boundingBox()
  await expect(rail.locator('section').first()).toHaveCSS('background-color', 'lch(9.232 0.85 272)')
  const status = rail.getByRole('button', { name: 'Active', exact: true })
  const statusBox = await status.boundingBox()
  expect(Math.abs(statusBox!.x - statusLabel!.x - 90)).toBeLessThanOrEqual(1)
  await expect(status).toHaveCSS('gap', '8px')
  const addOwner = rail.getByRole('button', { name: 'Add owner', exact: true })
  await expect(addOwner.locator('svg')).toHaveCSS('width', '18px')
  await expect(addOwner.locator('span').last()).toHaveCSS('color', 'lch(63.304 1.425 272)')
  await expect(rail.getByRole('button', { name: 'Change initiative target date', exact: true }).locator('span').last()).toHaveCSS('color', 'lch(63.304 1.425 272)')
  const addLabel = rail.getByRole('button', { name: 'Add label', exact: true })
  await expect(addLabel).toHaveCSS('font-size', '12px')
  await expect(addLabel).toHaveCSS('font-weight', '450')
  const labelBox = await addLabel.boundingBox()
  expect(Math.abs(labelBox!.x - statusBox!.x)).toBeLessThanOrEqual(1)
  await expect.poll(() => page.title()).toContain(`${initiative.name} › Overview`)
  const initiativeIcon = page.locator('.li-overview-icon')
  await expect(initiativeIcon).toHaveCSS('padding', '0px 8px')
  await expect(initiativeIcon).toHaveCSS('border-radius', '6px')
  await expect(initiativeIcon).toHaveCSS('background-color', /0\.175/)
  await expect(initiativeIcon.locator('svg')).toHaveCSS('width', '24px')
  const title = await page.locator('.li-title-input').boundingBox()
  expect(Math.abs(title!.x - 292.5)).toBeLessThanOrEqual(1)
  expect(Math.abs(title!.width - 691)).toBeLessThanOrEqual(1)
  const description = page.getByRole('textbox', { name: 'Initiative description', exact: true })
  const descriptionBox = await description.boundingBox()
  expect(Math.abs(descriptionBox!.x - (title!.x - 14))).toBeLessThanOrEqual(1)
  expect(Math.abs(descriptionBox!.width - (title!.width + 28))).toBeLessThanOrEqual(1)
  await description.click({ position: { x: 4, y: 20 } })
  await expect(description).toBeFocused()
  const latest = page.getByTestId('initiative-latest-update')
  await expect(latest).toBeVisible()
  await expect(latest).toContainText('Delivery remains on schedule.')
  await expect(latest).toContainText('On track')
  await expect(page.locator('.li-first-update')).toBeHidden()
  await rail.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(rail.locator('section').first().locator('dl')).toBeHidden()
  await rail.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(rail.locator('section').first().locator('dl')).toBeVisible()
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/desktop-initiative-overview.png`, animations: 'disabled' })
  await latest.getByRole('button', { name: 'Write initiative update', exact: true }).click()
  await expect(page).toHaveURL(/\/activity$/)
  await expect(page.getByText('Delivery remains on schedule.', { exact: true })).toBeVisible()
  await page.goto(`/${workspaceKey}/initiatives`)
  await expect(page.locator('.li-project-count__ring')).toBeVisible()
  await expect(page.locator('.li-project-count')).toHaveText('0 / 0')
})

test('gives an empty cycle directory its team context without an empty sidebar link', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const response = await request.get('/api/bootstrap', { headers })
  const data = await response.json() as BootstrapData
  const team = data.teams[0]
  const enabled = await request.patch(`/api/teams/${team.id}/cycle-settings`, { headers, data: { enabled: true, autoCreate: false } })
  expect(enabled.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/team/${team.key}/cycles`)
  await expect(page.locator('.cycle-team-breadcrumb')).toHaveText(team.name)
  await expect(page.locator('.flow-cycles-empty strong')).toHaveCSS('font-size', '20px')
  await expect(page.locator('.sidebar-team').getByRole('link', { name: 'Cycles', exact: true })).toHaveCount(0)
})
