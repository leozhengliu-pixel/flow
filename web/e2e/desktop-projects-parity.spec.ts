import { expect } from '@playwright/test'
import { test } from './workspace-fixture'
import type { BootstrapData, Initiative, Project } from '../src/types/flow'

test.skip(({ isMobile }) => isMobile, 'Desktop project geometry')
test.use({ viewport: { width: 1440, height: 900 } })

test('honors row properties, opens an icon-only date picker and keeps the overview rail', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const bootstrap = await request.get('/api/bootstrap', { headers })
  const data = await bootstrap.json() as BootstrapData
  const response = await request.post('/api/projects', { headers, data: { name: '[audit] Desktop project', summary: 'Delivery summary', teamIds: [data.teams[0].id] } })
  expect(response.ok()).toBeTruthy()
  const project = await response.json() as Project
  const milestone = await request.post(`/api/projects/${project.id}/milestones`, { headers, data: { name: 'Alpha' } })
  expect(milestone.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/projects/all`)
  const row = page.getByRole('row', { name: project.name, exact: true })
  await expect(row).toBeVisible()
  await expect(row.locator('.lp-project-row__milestone')).toBeVisible()
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  const display = page.getByRole('dialog', { name: 'Display options', exact: true })
  await display.locator('.lp-projects-display-select').filter({ has: page.locator('> span', { hasText: /^Grouping$/ }) }).getByRole('combobox').click()
  await page.getByRole('option', { name: 'No grouping', exact: true }).click()
  await expect(page.locator('.lp-project-group__header')).toHaveCount(0)
  await display.getByRole('button', { name: 'Summary', exact: true }).click()
  await display.getByRole('button', { name: 'Milestones', exact: true }).click()
  await expect(row.locator('small').filter({ hasText: 'Delivery summary' })).toBeHidden()
  await expect(row.locator('.lp-project-row__milestone')).toBeHidden()
  await display.getByRole('button', { name: 'Milestones', exact: true }).click()
  await page.keyboard.press('Escape')
  const date = row.locator('.lp-project-row__date')
  await expect(date).toHaveCSS('width', '28px')
  await expect(date.locator('.lp-project-row__date-icon')).toBeVisible()
  await date.click()
  await expect(page.getByRole('dialog').last()).toBeVisible()
  await page.keyboard.press('Escape')
  await row.locator('strong').click()
  const rail = page.getByRole('complementary', { name: 'Project sidebar', exact: true })
  await expect(rail).toBeVisible()
  const overview = await page.locator('.project-overview').boundingBox()
  expect(Math.abs(overview!.x - 292.5)).toBeLessThanOrEqual(1)
  expect(Math.abs(overview!.width - 691)).toBeLessThanOrEqual(1)
  const comment = await request.post(`/api/projects/${project.id}/comments`, { headers, data: { body: '[audit] Desktop activity comment' } })
  expect(comment.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/project/${project.slugId}/activity`)
  await expect(page.locator('.project-activity__month')).toBeVisible()
  await page.getByRole('link', { name: 'Issues', exact: true }).filter({ hasNot: page.locator('svg') }).click()
  const intro = page.locator('.project-issues__intro')
  await expect(intro).toBeVisible()
  const heading = await intro.locator('strong').boundingBox()
  expect(Math.abs(heading!.x - 468)).toBeLessThanOrEqual(1)
  expect(Math.abs(heading!.y - 454.95)).toBeLessThanOrEqual(1)
  await page.goto(`/${workspaceKey}/projects/all`)
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  await page.getByRole('tab', { name: 'Timeline', exact: true }).click()
  await page.keyboard.press('Escape')
  const timeline = page.getByRole('region', { name: 'Project timeline', exact: true })
  await expect(timeline.locator('.lp-project-timeline__group')).toHaveCount(0)
  await expect(timeline.locator('.lp-project-timeline__label')).toHaveCSS('width', '320px')
  await expect(timeline.locator('.lp-project-timeline__row')).toHaveCSS('height', '72px')
  await page.getByRole('button', { name: 'Timeline zoom', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Year', exact: true }).click()
  await expect(timeline).toHaveAttribute('data-zoom', 'year')
  await expect(timeline.locator('.lp-project-timeline__minor > span').first()).toHaveText(/^\d{1,2}$/)
  await page.reload()
  await expect(timeline).toHaveAttribute('data-zoom', 'year')
  await page.getByRole('button', { name: 'Center timeline on today', exact: true }).click()
})

test('shows persisted initiative updates with a docked, collapsible properties and activity rail', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const created = await request.post('/api/initiatives', { headers, data: { name: '[audit] Desktop initiative', status: 'active' } })
  expect(created.ok()).toBeTruthy()
  const initiative = await created.json() as Initiative
  const posted = await request.post(`/api/initiatives/${initiative.id}/updates`, { headers, data: { body: 'Delivery remains on schedule.', health: 'onTrack' } })
  expect(posted.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/initiative/${initiative.slugId}/overview`)
  const rail = page.locator('.li-detail-sidebar')
  await expect(rail).toBeVisible()
  await expect.poll(() => page.title()).toContain(`${initiative.name} › Overview`)
  const title = await page.locator('.li-title-input').boundingBox()
  expect(Math.abs(title!.x - 292.5)).toBeLessThanOrEqual(1)
  expect(Math.abs(title!.width - 691)).toBeLessThanOrEqual(1)
  const latest = page.getByTestId('initiative-latest-update')
  await expect(latest).toBeVisible()
  await expect(latest).toContainText('Delivery remains on schedule.')
  await expect(latest).toContainText('On track')
  await expect(page.locator('.li-first-update')).toBeHidden()
  await rail.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(rail.locator('section').first().locator('dl')).toBeHidden()
  await rail.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(rail.locator('section').first().locator('dl')).toBeVisible()
  await latest.getByRole('button', { name: 'Write initiative update', exact: true }).click()
  await expect(page).toHaveURL(/\/activity$/)
  await expect(page.getByText('Delivery remains on schedule.', { exact: true })).toBeVisible()
  await page.goto(`/${workspaceKey}/initiatives`)
  await expect(page.locator('.li-project-count__ring')).toBeVisible()
  await expect(page.locator('.li-project-count')).toHaveText('0 / 0')
})

test('gives an empty cycle directory its team context without an empty sidebar link', async ({ page, request, workspaceKey }) => {
  const headers = { 'X-Workspace-Key': workspaceKey }
  const response = await request.get('/api/bootstrap', { headers })
  const data = await response.json() as BootstrapData
  const team = data.teams[0]
  const enabled = await request.patch(`/api/teams/${team.id}/cycle-settings`, { headers, data: { enabled: true, autoCreate: false } })
  expect(enabled.ok()).toBeTruthy()
  await page.goto(`/${workspaceKey}/team/${team.key}/cycles`)
  await expect(page.locator('.cycle-team-breadcrumb')).toHaveText(team.name)
  await expect(page.locator('.flow-cycles-empty strong')).toHaveCSS('font-size', '20px')
  await expect(page.locator('.sidebar-team').getByRole('link', { name: 'Cycles', exact: true })).toHaveCount(0)
})
