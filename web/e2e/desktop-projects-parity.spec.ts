  await expect(page.locator('.lp-projects')).toHaveCSS('background-color', 'lch(5.52 0.4 272)')
  await expect(page.getByRole('columnheader', { name: 'Issues', exact: true }).locator('span')).toHaveCSS('padding-right', '12px')
  await expect(row.locator('.lp-project-row__milestone')).toBeVisible()
  await page.getByRole('button', { name: 'Display options', exact: true }).click()
  const display = page.getByRole('dialog', { name: 'Display options', exact: true })
  await expect(display.getByRole('button', { name: 'ID', exact: true })).toHaveCSS('padding', '0px 8px')
  await expect(display.getByRole('button', { name: 'ID', exact: true })).toHaveCSS('color', 'lch(64.714 1.425 272)')
  await expect(display.getByRole('heading', { name: 'List options', exact: true })).toHaveCSS('padding', '0px')
  await display.locator('.lp-projects-display-select').filter({ has: page.locator('> span', { hasText: /^Grouping$/ }) }).getByRole('combobox').click()
  await page.getByRole('option', { name: 'No grouping', exact: true }).click()
  await expect(page.locator('.lp-project-group__header')).toHaveCount(0)
  await expect(display.getByRole('combobox',{name:'Sub-grouping',exact:true})).toHaveCount(0)
  await expect(display.getByRole('checkbox',{name:'Show empty groups',exact:true})).toHaveCount(0)
  await display.locator('.lp-projects-display-select').filter({has:page.locator('> span',{hasText:/^Ordering$/})}).getByRole('combobox').click()
  await page.getByRole('option',{name:'Manual',exact:true}).click()
  const summary = display.getByRole('button', { name: 'Summary', exact: true })
  if (await summary.getAttribute('aria-pressed') === 'true') await summary.click()
  await display.getByRole('button', { name: 'Milestones', exact: true }).click()
  await expect(row.locator('small').filter({ hasText: 'Delivery summary' })).toBeHidden()
  await expect(row).toHaveAttribute('data-show-summary','false')
  await expect(row.locator('.lp-project-row__milestone')).toBeHidden()
  await display.getByRole('button', { name: 'Milestones', exact: true }).click()
  await page.keyboard.press('Escape')
  if (process.env.FLOW_CI_SHOTS) await page.screenshot({ path: `${process.env.FLOW_CI_SHOTS}/desktop-project-list.png`, animations: 'disabled' })
  const date = row.locator('.lp-project-row__date')
  await expect(date).toHaveCSS('width', '28px')
  await expect(date.locator('.lp-project-row__date-icon')).toBeVisible()
  await date.click()
  await expect(page.getByRole('dialog').last()).toBeVisible()
  await page.keyboard.press('Escape')
  await row.locator('strong').click()
  const rail = page.getByRole('complementary', { name: 'Project sidebar', exact: true })
  await expect(rail).toBeVisible()
  await expect(rail.locator('section').first()).toHaveCSS('background-color', 'lch(9.232 0.85 272)')
  await expect(rail.locator('section').first()).toHaveCSS('border-top-color', 'lch(16.793 1.93 272)')
  await expect(page.getByRole('textbox', { name: 'Project summary', exact: true })).toHaveCSS('color', 'lch(90.451 1.2 272)')
  const projectIcon = page.locator('.project-overview__icon')
  await expect(projectIcon).toHaveCSS('padding', '0px 8px')
  await expect(projectIcon).toHaveCSS('border-radius', '6px')
  await expect(projectIcon).toHaveCSS('background-color', /0\.175/)
  await expect(projectIcon.locator('svg')).toHaveCSS('width', '24px')
  const overview = await page.locator('.project-overview').boundingBox()
  expect(Math.abs(overview!.x - 292.5)).toBeLessThanOrEqual(1)
  expect(Math.abs(overview!.width - 691)).toBeLessThanOrEqual(1)
  const description = page.getByRole('textbox', { name: 'Project description', exact: true })
  const descriptionBox = await description.boundingBox()
  expect(Math.abs(descriptionBox!.x - (overview!.x - 14))).toBeLessThanOrEqual(1)
  expect(Math.abs(descriptionBox!.width - (overview!.width + 28))).toBeLessThanOrEqual(1)
  await description.click({ position: { x: 4, y: 20 } })
